def aplicar():
    print()
    print("=" * 60)
    print(" COMPLETANDO ESPANHOL ".center(60, "="))
    print("=" * 60)
    print()

    total_palavras = 0
    total_traduzidas = 0
    total_faltando = 0
    faltando_lista = []

    for arq_en in sorted(PASTA_INGLES.glob("*.json")):
        if arq_en.name == "modulos.json":
            continue

        nome = arq_en.name
        dados_en = json.loads(arq_en.read_text(encoding="utf-8"))
        dados_es = []

        for item in dados_en:
            pt = item.get("pt", "")
            total_palavras += 1

            if pt in DIC:
                es, pron = DIC[pt]
                dados_es.append({"pt": pt, "es": es, "pron": pron})
                total_traduzidas += 1
            else:
                dados_es.append({"pt": pt, "es": pt, "pron": ""})
                total_faltando += 1
                faltando_lista.append(f"{nome}: {pt}")

        caminho_es = PASTA_ESPANHOL / nome
        caminho_es.write_text(
            json.dumps(dados_es, ensure_ascii=False, indent=2),
            encoding="utf-8"
        )
        print(f"  OK: {nome} ({len(dados_es)} itens)")

    print()
    print("=" * 60)
    print(f" TOTAL: {total_palavras} palavras")
    print(f" Traduzidas: {total_traduzidas}")
    print(f" Faltando: {total_faltando}")
    print("=" * 60)

    if faltando_lista:
        arquivo_faltando = BASE / "espanhol_faltando.txt"
        arquivo_faltando.write_text(
            "\n".join(faltando_lista),
            encoding="utf-8"
        )
        print()
        print(f" Lista de palavras nao traduzidas: {arquivo_faltando}")


if __name__ == "__main__":
    aplicar()